/**
 * Intelligent translation resolver that looks up the target language,
 * falls back to base language (e.g. pt-PT -> pt, es-MX -> es, en-GB -> en),
 * then to English, then to Portuguese, or formats dynamically.
 */
export const getTranslation = (key: TranslationKey, langCode: string): string => {
  const normalized = langCode.toLowerCase();
  const primaryLang = normalized.split('-')[0];

  // 1. Check exact match
  if (TRANSLATIONS[normalized]?.[key]) {
    return TRANSLATIONS[normalized]![key]!;
  }

  // 2. Check base language (e.g., 'pt', 'es', 'en', 'zh')
  if (TRANSLATIONS[primaryLang]?.[key]) {
    return TRANSLATIONS[primaryLang]![key]!;
  }

  // 3. Fallback to English
  if (TRANSLATIONS['en']?.[key]) {
    return TRANSLATIONS['en']![key]!;
  }

  // 4. Fallback to Portuguese default
  if (TRANSLATIONS['pt']?.[key]) {
    return TRANSLATIONS['pt']![key]!;
  }

  return key;
};
